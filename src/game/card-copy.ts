export function cardDetails(copy:CardCopy):HTMLDetailsElement {
  const details=document.createElement('details');
  const summary=document.createElement('summary');
  summary.textContent='Когда полезно и что проверить';
  const context=document.createElement('p');
  context.textContent=copy.context;
  const observation=document.createElement('p');
  observation.textContent=copy.observe;
  details.append(summary,context,observation);
  return details;
}
