import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const [first, second, expectedTicks = '5000'] = process.argv.slice(2);
const [a, b] = await Promise.all([first, second].map(async file => JSON.parse(await readFile(file, 'utf8'))));
assert.deepEqual(a.config, b.config);
assert.equal(a.ticks, Number(expectedTicks));
assert.equal(a.engineVersion, b.engineVersion);
assert.equal(a.noFood, b.noFood);
assert.equal(b.ticks, a.ticks);
assert.equal(a.final.tick, a.ticks);
assert.equal(b.final.tick, b.ticks);
assert.deepEqual(a.errors, []);
assert.deepEqual(b.errors, []);
assert.match(a.hash, /^[0-9a-f]{64}$/);
assert.equal(a.hash, b.hash);
assert.deepEqual(a.checkpoints, b.checkpoints);
assert.ok(a.checkpoints.length > 2);
assert.equal(a.checkpoints[0].tick, 0);
assert.deepEqual(a.checkpoints.at(-1), { tick: a.ticks, hash: a.hash });
for (const checkpoint of a.checkpoints) assert.match(checkpoint.hash, /^[0-9a-f]{64}$/);
console.log(`DETERMINISM PASS: ${a.hash}`);
